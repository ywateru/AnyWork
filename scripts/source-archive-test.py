#!/usr/bin/env python3
"""Verify public source export boundaries in temporary repositories."""
import json
import pathlib
import shutil
import subprocess
import tarfile
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]


class SourceExport(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='anywork-source-')
        self.root = pathlib.Path(self.temp.name) / 'repo'
        (self.root / 'scripts').mkdir(parents=True)
        shutil.copy2(ROOT / 'scripts/source-archive.py', self.root / 'scripts/source-archive.py')
        (self.root / 'README.md').write_text('Public source\n')
        subprocess.run(['git', 'init', '-q', str(self.root)], check=True)
        subprocess.run(['git', '-C', str(self.root), 'add', '.'], check=True)

    def tearDown(self):
        self.temp.cleanup()

    def export(self, root=None, check=True):
        return subprocess.run(['python3', str((root or self.root) / 'scripts/source-archive.py')],
                              check=check, capture_output=True)

    def test_export_uses_tracked_public_files_and_neutral_metadata(self):
        for name in ['.env', 'docs/screenshots/session.png', '.remote-agent/access-token', '.anywork/access-token', 'auth.json']:
            path = self.root / name
            path.parent.mkdir(exist_ok=True, parents=True)
            path.write_text('private fixture')
            subprocess.run(['git', '-C', str(self.root), 'add', '-f', name], check=True)
        (self.root / 'docs/untracked-private.md').write_text('not reviewed')
        self.export()
        with tarfile.open(self.root / 'artifacts/anywork-source.tar.gz') as archive:
            self.assertEqual(set(archive.getnames()), {
                'anywork/README.md', 'anywork/scripts/source-archive.py',
                'anywork/SOURCE_MANIFEST.json',
            })
            self.assertTrue(all(m.uid == m.gid == 0 and not m.uname and not m.gname for m in archive))
            exported = pathlib.Path(self.temp.name) / 'exported'
            # This archive was generated by the fixture and its complete member list is checked above.
            if hasattr(tarfile, 'data_filter'):
                archive.extractall(exported, filter='data')
            else:
                archive.extractall(exported)
        source = exported / 'anywork'
        (source / 'personal-note.md').write_text('added after extraction')
        self.export(source)
        with tarfile.open(source / 'artifacts/anywork-source.tar.gz') as archive:
            self.assertNotIn('anywork/personal-note.md', archive.getnames())
            self.assertIn('anywork/README.md', archive.getnames())

    def test_untrusted_tree_and_unsafe_manifest_fail_closed(self):
        shutil.rmtree(self.root / '.git')
        self.assertNotEqual(self.export(check=False).returncode, 0)
        (self.root / 'SOURCE_MANIFEST.json').write_text(json.dumps(['../private.txt']))
        self.assertNotEqual(self.export(check=False).returncode, 0)
        self.assertFalse((self.root / 'artifacts/anywork-source.tar.gz').exists())

    def test_symlink_to_private_content_is_rejected(self):
        outside = pathlib.Path(self.temp.name) / 'private.txt'
        outside.write_text('not public')
        (self.root / 'link.txt').symlink_to(outside)
        subprocess.run(['git', '-C', str(self.root), 'add', 'link.txt'], check=True)
        self.assertNotEqual(self.export(check=False).returncode, 0)
        self.assertFalse((self.root / 'artifacts/anywork-source.tar.gz').exists())


if __name__ == '__main__':
    unittest.main(verbosity=2)
